# Generates src/wire/wire_logo.h: the H@N outline (from DejaVu Sans Bold) as 2D contours
# for the wireframe boot and loading screens. Units: 1/256 of the logo height.
import numpy as np, sys
from matplotlib.textpath import TextPath
from matplotlib.font_manager import FontProperties
fp = FontProperties(fname='/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf')
def contours(ch, step):
    tp = TextPath((0, 0), ch, size=1, prop=fp)
    out = []
    for p in tp.to_polygons(closed_only=True):
        p = np.array(p)
        if step is None:   # straight letters: keep the exact corners
            keep = [p[0]]
            for v in p[1:]:
                if np.hypot(*(v - keep[-1])) > 1e-3: keep.append(v)
            if np.hypot(*(keep[-1] - keep[0])) < 1e-3: keep.pop()
            out.append(np.array(keep)); continue
        seg = np.r_[0, np.cumsum(np.hypot(*np.diff(p, axis=0).T))]
        n = max(4, int(seg[-1] / step))
        t = np.linspace(0, seg[-1], n, endpoint=False)
        out.append(np.c_[np.interp(t, seg, p[:, 0]), np.interp(t, seg, p[:, 1])])
    return out, tp.get_extents()
shapes = []; x = 0
for ch, step in (('H', None), ('@', 0.085), ('N', None)):
    cs, e = contours(ch, step)
    for c in cs: shapes.append([(x + px - e.x0, py) for px, py in c])
    x += e.width + 0.12
allp = np.concatenate([np.array(s) for s in shapes])
cx = (allp[:, 0].min() + allp[:, 0].max()) / 2; cy = (allp[:, 1].min() + allp[:, 1].max()) / 2
h = allp[:, 1].max() - allp[:, 1].min()
pts = []; lens = []
for s in shapes:
    lens.append(len(s))
    for px, py in s: pts.append((round((px - cx) / h * 256), round(-(py - cy) / h * 256)))
w = (allp[:, 0].max() - allp[:, 0].min()) / h
o = open(sys.argv[1], 'w')
o.write('// Generated by tools/wire_logo.py: H@N outline, 1/256 of the logo height, centered.\n#pragma once\n#include <stdint.h>\n')
o.write('#define WIRE_LOGO_ASPECT %d   // width / height x 256\n' % round(w * 256))
o.write('static const uint8_t WIRE_LEN[] = { %s };\n' % ', '.join(map(str, lens)))
o.write('static const int16_t WIRE_PTS[][2] = {\n')
for i in range(0, len(pts), 8): o.write('  ' + ' '.join('{%d,%d},' % p for p in pts[i:i + 8]) + '\n')
o.write('};\n')
print(len(pts), 'points', lens, 'aspect', w)
