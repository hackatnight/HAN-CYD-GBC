import sys, numpy as np
from PIL import Image, ImageFilter
src = Image.open(sys.argv[1]).convert('RGB')
BAYER = (np.array([[0,8,2,10],[12,4,14,6],[3,11,1,9],[15,7,13,5]], np.float32)+0.5)/16-0.5

def compose(W, H, seed):
    fit = src.resize((W, round(src.height*W/src.width)), Image.LANCZOS)
    fit = fit.filter(ImageFilter.UnsharpMask(radius=1, percent=60, threshold=2))
    f = np.array(fit, np.float32); fh = f.shape[0]
    top = (H-fh)//2; bot = H-top-fh
    sky = np.median(f[:2], axis=0)                 # per-column sky at the top edge
    sky = np.array(Image.fromarray(sky[None].astype(np.uint8)).filter(ImageFilter.GaussianBlur(6)), np.float32)[0]
    low = np.median(f[-2:], axis=0)
    low = np.array(Image.fromarray(low[None].astype(np.uint8)).filter(ImageFilter.GaussianBlur(6)), np.float32)[0]
    night = np.array([10, 16, 26], np.float32)
    c = np.zeros((H, W, 3), np.float32)
    for y in range(top):                            # sky darkens upward into night
        t = (top-y)/max(1, top); c[y] = sky*(1-t*0.75) + night*t*0.75
    rng = np.random.default_rng(seed)
    for _ in range(int(W*top/900)):
        x, y = rng.integers(3, W-3), rng.integers(2, max(3, top-4))
        b = rng.uniform(0.5, 1.0); c[y, x] = c[y, x]*(1-b) + np.array([190, 205, 225])*b
    c[top:top+fh] = f
    for i in range(bot):                            # clouds sink into darkness
        t = (i+1)/max(1, bot); c[top+fh+i] = low*(1-t*0.8) + night*t*0.8
    for yy in (top, top+fh):
        for y in range(yy-2, yy+2):
            if 0 < y < H-1: c[y] = (c[y-1]+c[y]*2+c[y+1])/4
    Image.fromarray(np.clip(c,0,255).astype(np.uint8)).save(f'/tmp/logo/raw_{W}x{H}.png')
    by = np.tile(BAYER, (H//4+1, W//4+1))[:H, :W]
    q = np.zeros((H, W, 3), np.int32)
    for ch, bits in enumerate((5, 6, 5)):
        st = 255/(2**bits-1); q[..., ch] = np.clip(np.round(c[..., ch]/st + by*0.8), 0, 2**bits-1)
    v = (q[..., 0] << 11) | (q[..., 1] << 5) | q[..., 2]
    prev = np.stack([q[..., 0]*255//31, q[..., 1]*255//63, q[..., 2]*255//31], -1).astype(np.uint8)
    return v.astype(np.uint16), Image.fromarray(prev)

out = []
out.append('// H@N boot splash, RGB565 byte-swapped for the panel (generated by make_splash.py)\n#pragma once\n#include <stdint.h>\n')
for name, (W, H) in (('splash_land', (320, 240)), ('splash_port', (240, 320))):
    v, prev = compose(W, H, 7)
    prev.save(f'/tmp/logo/{name}.png'); prev.resize((W*3, H*3), Image.NEAREST).save(f'/tmp/logo/{name}_3x.png')
    sw = ((v >> 8) | (v << 8)) & 0xFFFF
    flat = sw.flatten()
    out.append(f'static const uint16_t {name}[{W*H}] = {{\n')
    for i in range(0, len(flat), 24):
        out.append(','.join('0x%04x' % x for x in flat[i:i+24]) + ',\n')
    out.append('};\n')
open(sys.argv[2], 'w').write(''.join(out))
