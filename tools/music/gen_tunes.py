# Writes src/music/tunes.h: the menu tunes as note data for the firmware's synthesizer
# (src/main.cpp, "Menu music"). Step codes: 0 = hold, 1 = rest, 2 = kick, 3 = hat, 4 = snare,
# 12 and up = MIDI note. Usage: python3 gen_tunes.py ../../src/music/tunes.h
import sys
from synth import render, parse, NOTE
from compose import song1
from starfield2 import a as starfield
KIND = {'sq': 0, 'tri': 1, 'saw': 2, 'noise': 3}
def code(tok):
    if tok == '-': return 0
    if tok == '.': return 1
    if tok in 'khx': return {'k': 2, 'h': 3, 'x': 4}[tok]
    return NOTE[tok[:-1]] + 12 * (int(tok[-1]) + 1)
out = ['// Generated by tools/music/gen_tunes.py. Original tunes written for H@N-CYD-GBC.', '#pragma once', '#include <stdint.h>', '']
tunes = []
for tid, (name, song) in enumerate((('Night Drive', song1), ('Starfield', starfield))):
    pcm = render(song)
    gain = 0.95 / max(abs(x) for x in pcm)   # same loudness as the previews
    chans = []
    for ci, c in enumerate(song['chans']):
        steps = [code(t) for t in parse(c['bars'])]
        arr = f'TUNE{tid}_CH{ci}'
        out.append(f'static const uint8_t {arr}[] = {{ ' + ', '.join(map(str, steps)) + ' };')
        v = c['voice']
        chans.append(f'{{ {KIND[v.kind]}, {v.vol}f, {v.duty}f, {v.decay}f, {v.sustain}f, {v.attack}f, {c.get("delay", 0)}, {arr}, {len(steps)} }}')
    out.append(f'static const TuneChannel TUNE{tid}_CHANS[] = {{ ' + ', '.join(chans) + ' };')
    tunes.append(f'{{ "{name}", {song["bpm"]}, {gain:.4f}f, TUNE{tid}_CHANS, {len(chans)} }}')
    out.append('')
out.insert(4, 'struct TuneChannel { uint8_t kind; float vol, duty, decay, sustain, attack; uint8_t delay; const uint8_t *steps; uint16_t n; };')
out.insert(5, 'struct Tune { const char *name; uint16_t bpm; float gain; const TuneChannel *ch; uint8_t nch; };')
out.append('static const Tune TUNES[] = { ' + ', '.join(tunes) + ' };')
out.append('#define NUM_TUNES (int)(sizeof TUNES / sizeof TUNES[0])')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
print('steps:', sum(len(parse(c['bars'])) for s in (song1, starfield) for c in s['chans']), 'bytes')
