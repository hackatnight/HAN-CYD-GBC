"""Writes src/gnuboy/patexp.h: tables that turn a Game Boy tile row into 8 pixels.

A tile row is two bytes, one bit of each pixel's color in each. PATEXP_N[b] holds, as
eight bytes, bit 7..0 of b (left to right on screen); PATEXP_M[b] holds them mirrored.
So a whole row is  PATEXP[lo] | (PATEXP[hi] << 1)  - each byte of the result is that
pixel's color 0..3, because every byte of a table entry is 0 or 1 and can't carry.

    python3 tools/gen_patexp.py
"""
import os

rows = []
for name, mirror in (('PATEXP_N', False), ('PATEXP_M', True)):
    vals = []
    for b in range(256):
        v = 0
        for j in range(8):                      # byte j of the result = pixel j
            bit = (b >> j) & 1 if mirror else (b >> (7 - j)) & 1
            v |= bit << (8 * j)                 # little-endian: byte j is bits 8j..8j+7
        vals.append(v)
    body = '\n'.join('\t' + ' '.join('0x%016XULL,' % v for v in vals[i:i + 4])
                     for i in range(0, 256, 4))
    rows.append('static const uint64_t DRAM_ATTR %s[256] = {\n%s\n};' % (name, body))

out = '''/* Generated by tools/gen_patexp.py - do not edit.
 * Tile row -> 8 pixels, one byte each (see the script for the trick). */
#ifndef PATEXP_H
#define PATEXP_H
#include <stdint.h>
#include "esp_attr.h"   /* DRAM_ATTR: keep the tables in fast RAM, not flash */

%s

%s

#endif
''' % (rows[0], rows[1])
path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'src', 'gnuboy', 'patexp.h')
open(path, 'w').write(out)
print('wrote', path, len(out), 'bytes')
